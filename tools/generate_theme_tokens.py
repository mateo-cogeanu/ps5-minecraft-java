#!/usr/bin/env python3
"""Generate both native and web theme values from the maintained launcher palette."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def outputs():
    t=json.loads((ROOT/'client/launcher/theme-tokens.json').read_text())
    hues=','.join('{'+','.join(map(str,h))+'}' for h in t['hues'])
    native='// Generated by tools/generate_theme_tokens.py; do not edit.\n#pragma once\nnamespace prospero_theme {inline constexpr int hues[6][3]={'+hues+'};}\n'
    java='''// Generated by tools/generate_theme_tokens.py; do not edit.
import java.util.*;
final class ProsperoTheme {
 static final int[][] HUES={HUES_VALUE};
 static final String[] NAMES=NAMES_VALUE;
 static String color(int selected,int value){
  int r=value>>16&255,g=value>>8&255,b=value&255;
  if(selected>0&&selected<6&&g>r&&g>b){int low=Math.min(r,b),span=g-low;int[] h=HUES[selected];value=(low+span*h[0]/255)<<16|(low+span*h[1]/255)<<8|(low+span*h[2]/255);}
  return String.format(Locale.ROOT,"#%06x",value);
 }
 static Map<String,String> web(int selected){return Map.of(WEB_VALUE);}
}
'''.replace('HUES_VALUE',hues).replace('NAMES_VALUE','{'+','.join(json.dumps(n) for n in t['names'])+'}').replace('WEB_VALUE',','.join(json.dumps(k)+',color(selected,0x'+v+')' for k,v in t['web'].items()))
    return {ROOT/'client/launcher/theme_tokens.hpp':native,ROOT/'client/launcher/java/ProsperoTheme.java':java}
if __name__=='__main__':
    for p,s in outputs().items():p.write_text(s)
